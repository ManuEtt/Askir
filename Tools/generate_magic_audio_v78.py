"""Generate two original PCM spell cues; no external samples or recordings."""
from pathlib import Path
import argparse
import hashlib
import json
import math
import struct
import wave
ROOT=Path(__file__).resolve().parents[1]
RATE=48000

def samples(kind):
    duration=.7 if kind=='SpellCast' else .45
    result=[]
    for i in range(round(duration*RATE)):
        t=i/RATE;p=t/duration;env=math.sin(math.pi*p)**2
        if kind=='SpellCast':
            value=.48*env*(math.sin(2*math.pi*(230*t+170*t*t))+.3*math.sin(2*math.pi*690*t))
        else:
            value=.6*env*math.exp(-p*3)*(math.sin(2*math.pi*110*t)+.45*math.sin(2*math.pi*333*t))
        result.append(round(max(-.95,min(.95,value))*32767))
    return result

def validate(path):
    with wave.open(str(path),'rb') as f:
        if(f.getnchannels(),f.getsampwidth(),f.getframerate())!=(1,2,RATE):raise ValueError('Unexpected PCM format')
        data=f.readframes(f.getnframes());values=struct.unpack('<'+'h'*(len(data)//2),data)
    rms=math.sqrt(sum((v/32767)**2 for v in values)/len(values));peak=max(abs(v) for v in values)/32767
    if not .01<rms<.5 or peak>=.95 or values[0]!=0 or values[-1]!=0:raise ValueError('Invalid signal envelope')
    return {'path':path.name,'duration_seconds':len(values)/RATE,'rms':rms,'peak':peak,'sha256':hashlib.sha256(path.read_bytes()).hexdigest()}

def main():
    parser=argparse.ArgumentParser(description=__doc__);parser.add_argument('--validate-only',action='store_true');args=parser.parse_args()
    folder=ROOT/'ArtSource/Audio_V78';folder.mkdir(parents=True,exist_ok=True);rows=[]
    for kind in ('SpellCast','SpellImpact'):
        path=folder/('S_'+kind+'.wav')
        if not args.validate_only:
            with wave.open(str(path),'wb') as f:
                f.setnchannels(1);f.setsampwidth(2);f.setframerate(RATE);values=samples(kind);f.writeframes(struct.pack('<'+'h'*len(values),*values))
        rows.append(validate(path))
    if not args.validate_only:
        (folder/'audio_manifest.json').write_text(json.dumps({'origin':'Original procedural oscillator composition generated by ASKIR development tooling','license':'CC0-1.0','assets':rows,'unreal_import':'Nicht ausgeführt'},indent=2))
        (folder/'LICENSE.txt').write_text('Original procedural ASKIR V78 sound sources. CC0-1.0. No external samples or recordings.\n')
    print(json.dumps({'assets':len(rows),'status':'Bestanden','unreal_import':'Nicht ausgeführt'}))
if __name__=='__main__':main()
