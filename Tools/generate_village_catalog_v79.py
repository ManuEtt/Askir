"""Generate native village catalog constants from the same data used by UE import."""
from __future__ import annotations
import argparse
import json
import math
from pathlib import Path
import re
ROOT = Path(__file__).resolve().parents[1]
CONTRACT = ROOT / 'Production/Economy/dornfeld_v79.json'
GENERATED = ROOT / 'Source/Askir/Economy/AskirVillageEconomyCatalog.generated.inl'


def load_contract(path=CONTRACT):
    data = json.loads(Path(path).read_text(encoding='utf-8'))
    if data.get('version') != 'V79' or data.get('asset_root') != '/Game/Askir/V79/Items':
        raise ValueError('Wrong catalog version/package root')
    if not isinstance(data.get('merchant_id'), str) or not re.fullmatch(r'[A-Za-z0-9_]+', data['merchant_id']):
        raise ValueError('Merchant needs a stable persistent ID')
    def integer(value, minimum, maximum):
        if type(value) is not int or not minimum <= value <= maximum: raise ValueError('Integer outside catalog bounds')
    def number(value, minimum, maximum):
        if type(value) not in (int, float) or not math.isfinite(value) or not minimum <= value <= maximum: raise ValueError('Nonfinite/out-of-range number')
    def position(value):
        if not isinstance(value, list) or len(value) != 3: raise ValueError('Position must be XYZ')
        for coordinate in value: number(coordinate, -2300, 3500)
    integer(data['merchant_gold'], 0, 2147483647);number(data['sell_back_ratio'], 0.01, 1)
    position(data['merchant_position']);position(data['station_position'])
    for name in ('merchant_name', 'station_name'):
        if not isinstance(data[name], str) or not data[name].strip(): raise ValueError('Missing interaction name')
    items={}
    for item in data['items']:
        name=item['id']
        if not isinstance(name,str) or not re.fullmatch(r'[a-z0-9_]+',name) or name in items: raise ValueError('Invalid/duplicate item ID')
        if item['type'] not in ('Misc','Consumable','Weapon','Armor'): raise ValueError('Village trading cannot include quest items')
        for field in ('name','description'):
            if not isinstance(item[field],str) or not item[field].strip():raise ValueError('Missing display text')
        integer(item['stack'],1,999);integer(item['value'],1,100000);integer(item['stock'],0,999);integer(item['max_stock'],item['stock'],999)
        for field in ('weight','damage','heal'):number(item[field],0,1000)
        number(item['attack_range'],1,1000);number(item['attack_cooldown'],0.05,10)
        if item['type']=='Consumable' and item['heal']<=0:raise ValueError('Consumable needs a gameplay effect')
        if item['type']=='Weapon' and (item['damage']<=0 or item['stack']!=1):raise ValueError('Weapon needs damage and individual slot')
        items[name]=item
    if not items:raise ValueError('Empty village item catalog')
    def entry(value):
        if value['item_id'] not in items:raise ValueError('Unresolved recipe/pickup item')
        integer(value['quantity'],1,999)
    recipes=set()
    for recipe in data['recipes']:
        if not re.fullmatch(r'[a-z0-9_]+',recipe['id']) or recipe['id'] in recipes:raise ValueError('Invalid/duplicate recipe ID')
        integer(recipe['required_skill'],1,100)
        if type(recipe['known_by_default']) is not bool:raise ValueError('Recipe knowledge flag must be boolean')
        if not 1<=len(recipe['ingredients'])<=2:raise ValueError('Village recipe expects one or two ingredients')
        ingredient_ids=set()
        for ingredient in recipe['ingredients']:
            entry(ingredient)
            if ingredient['item_id'] in ingredient_ids:raise ValueError('Duplicate recipe ingredient')
            ingredient_ids.add(ingredient['item_id'])
        entry(recipe['result'])
        if recipe['result']['item_id'] in ingredient_ids:raise ValueError('Self-producing ingredient recipe')
        recipes.add(recipe['id'])
    ids={data['merchant_id']}
    for pickup in data['resource_pickups']:
        if not re.fullmatch(r'[A-Za-z0-9_]+',pickup['id']) or pickup['id'] in ids:raise ValueError('Duplicate persistent source')
        ids.add(pickup['id']);entry(pickup);position(pickup['position'])
    return data


def text_literal(value):
    return 'TEXT('+json.dumps(value,ensure_ascii=False)+')'


def generated_text(data):
    lines=['// Generated by Tools/generate_village_catalog_v79.py; do not edit by hand.','constexpr FAskirVillageItemSpec VillageItems[] = {']
    for item in data['items']:
        lines.append('    {'+', '.join([text_literal(item['id']),str(item['value']),str(item['stock']),str(item['max_stock'])])+'},')
    lines.extend(['};','constexpr FAskirVillageRecipeSpec VillageRecipes[] = {'])
    for recipe in data['recipes']:
        ingredients=list(recipe['ingredients'])+[{'item_id':'','quantity':0}]*(2-len(recipe['ingredients']))
        values=[text_literal(recipe['id']),str(recipe['required_skill']),'true' if recipe['known_by_default'] else 'false']
        for entry in ingredients:values.extend([text_literal(entry['item_id']),str(entry['quantity'])])
        values.extend([text_literal(recipe['result']['item_id']),str(recipe['result']['quantity'])])
        lines.append('    {'+', '.join(values)+'},')
    lines.extend(['};','constexpr int32 VillageMerchantGold = '+str(data['merchant_gold'])+';','constexpr float VillageSellBackRatio = '+str(data['sell_back_ratio'])+'f;','constexpr const TCHAR* VillageMerchantID = '+text_literal(data['merchant_id'])+';',''])
    return '\n'.join(lines)


def main(argv=None):
    parser=argparse.ArgumentParser(description=__doc__);parser.add_argument('--check',action='store_true');args=parser.parse_args(argv)
    data=load_contract();expected=generated_text(data)
    if args.check:
        if not GENERATED.is_file() or GENERATED.read_text(encoding='utf-8')!=expected:raise RuntimeError('Native village catalog is stale; regenerate first')
    else:GENERATED.write_text(expected,encoding='utf-8')
    print('Village catalog: '+str(len(data['items']))+' items, '+str(len(data['recipes']))+' inventory recipes; '+('synchronized' if args.check else 'generated'))
    return 0

if __name__=='__main__':raise SystemExit(main())
